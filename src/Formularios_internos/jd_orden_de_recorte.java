    private void btn_eliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_eliminarActionPerformed
        int fila = jtabla.getSelectedRow();
        if (fila == -1) {
            JOptionPane.showMessageDialog(null, "Seleccione un registro");
        } else {
            int dialogButton = JOptionPane.YES_NO_OPTION;
            int dialogResult = JOptionPane.showConfirmDialog(null, "Desea eliminar este abono?", "Alerta", dialogButton);
            if (dialogResult == JOptionPane.YES_OPTION) {
                try {
                    DefaultTableModel modelo = (DefaultTableModel) jtabla.getModel();
                    String id = (String) modelo.getValueAt(fila, 0);//suponiendo que el id lo muestras en la primera columna
                    double abonoEliminado = Double.parseDouble(Metodos.metodos.EliminaCaracteres("" + modelo.getValueAt(fila, 2), "."));
                    double saldo = Double.parseDouble(Metodos.metodos.EliminaCaracteres(lbl_total_saldo.getText(), "."));
                    double totalAbonos = Double.parseDouble(Metodos.metodos.EliminaCaracteres(lbl_total_entregado.getText(), "."));
                    lbl_total_entregado.setText(metodos.formateador_decimal_punto_para_decimal().format(totalAbonos - abonoEliminado));
                    lbl_total_saldo.setText(metodos.formateador_decimal_punto_para_decimal().format(saldo + abonoEliminado));
                    DB_consultas_R_D.eliminar("recortes_detalle", id);
                    modelo.removeRow(fila);
                    frm_Recortes.btn_actualizar.doClick();
                } catch (Exception e) {
                    e.printStackTrace();
                }
            }
        }
    }//GEN-LAST:event_btn_eliminarActionPerformed

