    private void btn_guardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_guardarActionPerformed
        if (txt_cantidad.getText().isEmpty()) {
            txt_cantidad.setBackground(Color.pink);
        } else {
            if (validaSaldo()) {
                Recortes_detallle rec = new Recortes_detallle();
                DB_Recortes_detalle db_rec = new DB_Recortes_detalle();
                rec.setId(Integer.parseInt(lbl_id_orden_recorte.getText()));
                rec.setId_cabecera(Integer.parseInt(lbl_id_recorte.getText()));
                rec.setId_user(frm_main.id_user);
                rec.setCantidad(Double.parseDouble(txt_cantidad.getText()));
                rec.setId_contacto(Integer.parseInt(lbl_id_cliente.getText()));
                rec.setObservacion(txt_observaciones.getText());
                int dia, mes, ano;
                ano = jdate_fecha.getCalendar().get(Calendar.YEAR);
                mes = jdate_fecha.getCalendar().get(Calendar.MARCH) + 1;
                dia = jdate_fecha.getCalendar().get(Calendar.DAY_OF_MONTH);
                rec.setFecha(ano + "-" + mes + "-" + dia);
                
                rec.setHora(DB_consultas_R_D.obtener_hora());
                rec.setCodigo(txt_codigo.getText());
                
                rec.setEstado(0);
                if (db_rec.Guardar(rec) > 0) {

                    frm_Recortes.btn_actualizar.doClick();
                    lbl_id_orden_recorte.setText(DB_consultas_R_D.cargarId("recortes_detalle"));
                    txt_observaciones.setText("");

                    String id = "" + rec.getId();//suponiendo que el id lo muestras en la primera columna

                    String cad = new File("").getAbsolutePath() + "/src/reportes/ImprimirRecorte.jrxml";
                    if (!cad.equals("")) {
                        Connection cn = DB_consultas_R_D.getConexion();
                        JasperReport report = null;
                        Map p = new HashMap();
                        p.put("SUBREPORT_DIR", new File("").getAbsolutePath() + "/src/reportes/");
                        p.put("id_factura", Integer.parseInt(id));
                        try {
                            try {
                                report = JasperCompileManager.compileReport(cad);
                            } catch (Exception e) {
                                JOptionPane.showMessageDialog(this, e);
                            }
                            JasperPrint print = JasperFillManager.fillReport(report, p, cn);
                            JasperViewer view = new JasperViewer(print, false);
                            cn.close();
                            JDialog dialog = new JDialog(this);//the owner
                            metodos.addEscapeListenerWindowDialog(dialog);
                            dialog.setContentPane(view.getContentPane());
                            dialog.setSize(view.getSize());
                            dialog.setModal(true);
                            dialog.setLocationRelativeTo(this);
                            dialog.setTitle("Recortes");
                            dialog.setVisible(true);

                        } catch (Exception e) {
                            e.printStackTrace();
                        }
                    }

                }

                jd_orden_de_recorte.modelo_ver_entregas.addRow(new Object[]{rec.getId(), lbl_user.getText(),
                    metodos.formateador_decimal_punto_para_decimal().format(rec.getCantidad()),
                    rec.getFecha(), rec.getHora()});

                double cantidad = rec.getCantidad();
                double saldo = Double.parseDouble(lbl_total_saldo.getText());
                double entregado = Double.parseDouble(lbl_total_entregado.getText());
                lbl_total_entregado.setText(metodos.formateador_decimal_punto_para_decimal().format(entregado + cantidad));
                lbl_total_saldo.setText(metodos.formateador_decimal_punto_para_decimal().format(saldo - cantidad));
                lbl_id_orden_recorte.setText(DB_consultas_R_D.cargarId("recortes_detalle"));
                txt_cantidad.setText("");

            }
        }
    }//GEN-LAST:event_btn_guardarActionPerformed
    public boolean validaSaldo() {
        double saldo = Double.parseDouble(metodos.EliminaCaracteres(lbl_total_saldo.getText(), "."));
        double cantidad = Double.parseDouble(txt_cantidad.getText());
        if (cantidad > saldo) {
            JOptionPane.showMessageDialog(this, "La cantidad ingresada supera el saldo de la factura \nVerifique los valores ingresados");
            txt_cantidad.setText("");
            txt_cantidad.requestFocus();
            return false;
        }
        return true;
    }
