    private void btn_guardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_guardarActionPerformed

        int guardo_cabecera = 0;
        DB_Traslados_productos db_traslado = new DB_Traslados_productos();
        Traslados_productos obj = new Traslados_productos();
        DBstock_productos dbStock = new DBstock_productos();

        // Obtener bodegas
        int idBodegaOrigen = 0;
        int idBodegaDestino = 0;
        try {
            idBodegaOrigen = jbox_bodega_origen.getItemAt(jbox_bodega_origen.getSelectedIndex()).getId();
        } catch (Exception e) {
            idBodegaOrigen = id_bodega_origen;
        }
        try {
            idBodegaDestino = jbox_bodega_destino.getItemAt(jbox_bodega_destino.getSelectedIndex()).getId();
        } catch (Exception e) {
            idBodegaDestino = id_bodega_destino;
        }

        // Validar que origen y destino sean diferentes
        if (idBodegaOrigen == idBodegaDestino) {
            JOptionPane.showMessageDialog(this,
                    "La bodega de origen y destino no pueden ser iguales.",
                    "Error de validación",
                    JOptionPane.WARNING_MESSAGE);
            return;
        }

        obj.setId_bodega_origen(idBodegaOrigen);
        obj.setId_bodega_destino(idBodegaDestino);
        obj.setId_producto(id_producto);

        double cantidad = Double.parseDouble(txt_cantidad.getText());
        obj.setCantidad(cantidad);
        obj.setId_user(frm_main.id_user);
        obj.setObservacion(txt_observacion.getText());

        int hora, minutos, segundos;
        int dia, mes, ano;
        ano = jdate_fecha.getCalendar().get(Calendar.YEAR);
        mes = jdate_fecha.getCalendar().get(Calendar.MONTH) + 1;
        dia = jdate_fecha.getCalendar().get(Calendar.DAY_OF_MONTH);
        hora = jdate_fecha.getCalendar().get(Calendar.HOUR_OF_DAY);
        minutos = jdate_fecha.getCalendar().get(Calendar.MINUTE);
        segundos = jdate_fecha.getCalendar().get(Calendar.SECOND);
        obj.setFecha("'" + ano + "-" + mes + "-" + dia + "'");
        obj.setHora("'" + hora + ":" + minutos + ":" + segundos + "'");

        int idTraslado = Integer.parseInt(lbl_id_traslado.getText());
        obj.setId(idTraslado);

        boolean esEdicion = DB_consultas_R_D.consultarId(lbl_id_traslado.getText(), "traslados_productos") == 1;

        if (esEdicion) {
            // ════════════════════════════════════════════════════════════
            // EDICIÓN: Reversar traslado anterior antes de actualizar
            // ════════════════════════════════════════════════════════════
            reversarTrasladoAnterior(idTraslado, dbStock);

            guardo_cabecera = db_traslado.Actualizar(obj);
        } else {
            guardo_cabecera = db_traslado.Guardar(obj);
        }

        if (guardo_cabecera > 0) {
            // ════════════════════════════════════════════════════════════
            // INTEGRACIÓN STOCK: Registrar traslado (salida + entrada)
            // ════════════════════════════════════════════════════════════
            String obsTraslado = "Traslado #" + idTraslado;
            if (!txt_observacion.getText().isEmpty()) {
                obsTraslado += " - " + txt_observacion.getText();
            }

            // Salida de bodega origen
            dbStock.trasladoSalida(
                    id_producto,
                    idBodegaOrigen,
                    frm_main.id_user,
                    cantidad,
                    idTraslado,
                    obsTraslado + " (Salida)"
            );

            // Entrada a bodega destino
            dbStock.trasladoEntrada(
                    id_producto,
                    idBodegaDestino,
                    frm_main.id_user,
                    cantidad,
                    idTraslado,
                    obsTraslado + " (Entrada)"
            );

            System.out.println("GUARDO EL TRASLADO CON STOCK");
        }

        frm_traslado_productos_entre_bodegas.btn_actualizar.doClick();
        this.dispose();

    }//GEN-LAST:event_btn_guardarActionPerformed
