// MÉTODO AUXILIAR: Reversar traslado anterior (para ediciones)
// ════════════════════════════════════════════════════════════════════════════

    private void reversarTrasladoAnterior(int idTraslado, DBstock_productos dbStock) {
        String sql = "SELECT id_producto, id_bodega_origen, id_bodega_destino, cantidad "
                + "FROM traslados_productos WHERE id = " + idTraslado;

        ResultSet rs = DB_consultas_R_D.getTabla(sql);
        try {
            if (rs.next()) {
                int idProductoAnt = rs.getInt("id_producto");
                int idBodegaOrigenAnt = rs.getInt("id_bodega_origen");
                int idBodegaDestinoAnt = rs.getInt("id_bodega_destino");
                double cantidadAnt = rs.getDouble("cantidad");

                String obsAnulacion = "Reversión por edición - Traslado #" + idTraslado;

                // Anular salida anterior (devolver a origen)
                dbStock.anularTrasladoSalida(
                        idProductoAnt,
                        idBodegaOrigenAnt,
                        frm_main.id_user,
                        cantidadAnt,
                        idTraslado,
                        obsAnulacion
                );

                // Anular entrada anterior (quitar de destino)
                dbStock.anularTrasladoEntrada(
                        idProductoAnt,
                        idBodegaDestinoAnt,
                        frm_main.id_user,
                        cantidadAnt,
                        idTraslado,
                        obsAnulacion
                );
            }
            rs.close();
        } catch (SQLException e) {
            System.out.println("Error reversando traslado anterior: " + e);
        }
    }
