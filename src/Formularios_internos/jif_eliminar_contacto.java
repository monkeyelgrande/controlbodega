    private void btn_cambioActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_cambioActionPerformed

        if (lbl_id_cliente.getText().equals(lbl_id_nuevo_cliente.getText())) {
            JOptionPane.showMessageDialog(this, "NO esta permitido eliminar seleccionar el mismo cliente para este proceso");
        } else {
            Connection con = null;
            String SSQL = "update facturas_cabeceras "
                    + "set id_contacto=" + lbl_id_nuevo_cliente.getText() + " "
                    + "where id_contacto=  " + lbl_id_cliente.getText() + ";\n"
                    + "update cotizaciones_cabeceras "
                    + "set id_contacto=" + lbl_id_nuevo_cliente.getText() + " "
                    + "where id_contacto=  " + lbl_id_cliente.getText() + ";";
            try {
                con = getConexion();
                PreparedStatement psql = con.prepareStatement(SSQL);
                psql.executeUpdate();
                psql.close();
                con.close();
                this.dispose();
            } catch (SQLException e) {
                JOptionPane.showMessageDialog(null, "No se puede actualziar: \n" + e);
            }
        }

    }//GEN-LAST:event_btn_cambioActionPerformed

