    public void actualizar() {
        String consulta = "select * from facturas_cabeceras where id_contacto=" + id_cliente;
        ResultSet rs = DB_consultas_R_D.getTabla(consulta);
        modelo_creditos.setColumnIdentifiers(new Object[]{"id", "Códgio", "Fecha", "Observación"});
        try {
            while (rs.next()) {
                // añade los resultado a al modelo de tabla
                modelo_creditos.addRow(new Object[]{rs.getString("id"), rs.getString("codigo"), rs.getString("fecha"), rs.getString("observacion")});
            }
            rs.close();
            // asigna el modelo a la tabla
        } catch (Exception e) {
            System.out.println(e);
        }
        jtabla_creditos.setModel(modelo_creditos);

        // Cotizaciones
        consulta = "select * from cotizaciones_cabeceras where id_contacto=" + id_cliente;
        rs = DB_consultas_R_D.getTabla(consulta);
        modelo_cotizaciones.setColumnIdentifiers(new Object[]{"id", "Códgio", "Fecha", "Observación"});
        try {
            while (rs.next()) {
                // añade los resultado a al modelo de tabla
                modelo_cotizaciones.addRow(new Object[]{rs.getString("id"), rs.getString("codigo"), rs.getString("fecha"), rs.getString("observacion")});
            }
            rs.close();
            // asigna el modelo a la tabla
        } catch (Exception e) {
            System.out.println(e);
        }
        jtabla_cotizaciones.setModel(modelo_cotizaciones);
    }

