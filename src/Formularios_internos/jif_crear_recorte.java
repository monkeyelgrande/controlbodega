    private void btn_guardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_guardarActionPerformed
        if (lbl_id_producto.getText().equals("-") || txt_total.getText().equals("")) {
            JOptionPane.showMessageDialog(this, "Por favor agregue  un producto y cantidad");
            txt_codigo_barras.requestFocus();
        } else {
            DB_Recortes_cabecera db_recorte = new DB_Recortes_cabecera();
            Recortes_cabeceras recorte = new Recortes_cabeceras();

            recorte.setId(Integer.parseInt(lbl_id.getText()));
            recorte.setId_producto(Integer.parseInt(lbl_id_producto.getText()));
            recorte.setId_user(frm_main.id_user);
            recorte.setCantidad(Double.parseDouble(txt_total.getText()));

            int dia, mes, ano;
            ano = jdate_fecha_entrada.getCalendar().get(Calendar.YEAR);
            mes = jdate_fecha_entrada.getCalendar().get(Calendar.MARCH) + 1;
            dia = jdate_fecha_entrada.getCalendar().get(Calendar.DAY_OF_MONTH);

            recorte.setFecha(ano + "-" + mes + "-" + dia);
            recorte.setHora(DB_consultas_R_D.obtener_hora());
            recorte.setObservacion(txt_observacion.getText());
            if (DB_consultas_R_D.consultarId(lbl_id.getText(), "recortes_cabecera") == 1) {
                db_recorte.Actualizar(recorte);
            } else {
                db_recorte.Guardar(recorte);
            }

            frm_Recortes.btn_actualizar.doClick();
            if (chk_cerrar.isSelected()) {
                this.dispose();
            } else {
                lbl_id.setText(DB_consultas_R_D.cargarId("recortes_cabecera"));
            }

        }
    }//GEN-LAST:event_btn_guardarActionPerformed

