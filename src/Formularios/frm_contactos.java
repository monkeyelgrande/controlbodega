    public void actualizar() {

        // Limpiar el modelo correctamente
        modelo.setRowCount(0);

        // Definir columnas
        modelo.setColumnIdentifiers(new Object[]{
            "ID", "Nombre", "Cédula", "Celular", "Proveedor"
        });

        String sql = "SELECT id, nombre, cedula, contacto, proveedor "
                + "FROM contactos "
                + "ORDER BY nombre";

        try (ResultSet rs = DB_consultas_R_D.getTabla(sql)) {

            while (rs.next()) {

                // Si proveedor es boolean o int, lo mostramos más legible
                String esProveedor = rs.getBoolean("proveedor") ? "Sí" : "No";

                modelo.addRow(new Object[]{
                    rs.getString("id"),
                    rs.getString("nombre"),
                    rs.getString("cedula"),
                    rs.getString("contacto"),
                    esProveedor
                });
            }

            jtabla.setModel(modelo);

        } catch (Exception e) {
            System.out.println("Error al actualizar contactos: " + e.getMessage());
        }
    }

