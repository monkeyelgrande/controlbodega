    private void btn_eliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_eliminarActionPerformed
        int fila = jtabla.getSelectedRow();
        if (fila == -1) {
            JOptionPane.showMessageDialog(null, "Seleccione un registro");
        } else {
            String id = jtabla.getValueAt(fila, 0).toString();//suponiendo que el id lo muestras en la primera columna

            if (DB_consultas_R_D.TieneCreditosOCotizaciones(id) > 0) {
                JOptionPane.showMessageDialog(this, "El cliente tiene créditos asociados\n"
                        + "Se abrira la ventana correspondiente a reasignación de cliente");

                jif_eliminar_contacto jif = new jif_eliminar_contacto(null, closable, id);

                jif.lbl_cliente.setText(jtabla.getValueAt(fila, 1).toString());
                jif.lbl_id_cliente.setText(id);
                jif.show();
            }
            int dialogButton = JOptionPane.YES_NO_OPTION;
            int dialogResult = JOptionPane.showConfirmDialog(null, "Desea eliminar este contacto?", "Alerta", dialogButton);
            if (dialogResult == JOptionPane.YES_OPTION) {
                try {
                    DefaultTableModel modelo = (DefaultTableModel) jtabla.getModel();
                    id = (String) jtabla.getValueAt(fila, 0);//suponiendo que el id lo muestras en la primera columna
                    DB_consultas_R_D.eliminar("contactos", id);
                    for (int i = 0; i < modelo.getRowCount(); i++) {
                        if (modelo.getValueAt(i, 0).equals(id)) {
                            modelo.removeRow(i);
                            break;
                        }
                    }
                } catch (Exception e) {
                    e.printStackTrace();
                }
            }
        }
    }//GEN-LAST:event_btn_eliminarActionPerformed

    private void btn_editarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_editarActionPerformed
        jif_crear_contacto = new jif_crear_contactos();
        int fila = jtabla.getSelectedRow();
        if (fila < 0) {
            JOptionPane.showMessageDialog(this, "Seleccione un registro");
        } else {
            String id = jtabla.getValueAt(fila, 0).toString();

            ResultSet rs = DB_consultas_R_D.getTabla("select * from contactos where id =" + id);
            try {
                while (rs.next()) {
                    jif_crear_contactos.txt_id_cliente.setText(rs.getString("id"));
                    jif_crear_contactos.txt_nombre.setText(rs.getString("nombre"));
                    jif_crear_contactos.txt_cedula.setText(rs.getString("cedula"));

                    if (rs.getInt("proveedor") == 1) {
                        jif_crear_contactos.chk_proveedor.setSelected(true);
                    }
                }
                rs.close();

            } catch (SQLException ex) {
                Logger.getLogger(frm_contactos.class.getName()).log(Level.SEVERE, null, ex);
            }
            if (ver) {
                jif_crear_contacto.txt_nombre.setEnabled(false);
                jif_crear_contacto.txt_cedula.setEnabled(false);
                jif_crear_contacto.txt_contacto.setEnabled(false);

                jif_crear_contacto.btn_guardar.setEnabled(false);
                jif_crear_contacto.btn_limpiar.setEnabled(false);
                jif_crear_contacto.chk_cerrar.setEnabled(false);
                jif_crear_contacto.btn_editar.setVisible(true);
            }
            ver = false;
            jif_crear_contacto.show();

            jif_crear_contactos.txt_nombre.requestFocus();

        }

    }//GEN-LAST:event_btn_editarActionPerformed

