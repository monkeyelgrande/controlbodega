    private void btn_restablecerActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_restablecerActionPerformed
        if (DB_consultas_R_D.validar_admin()) {
            int fila = jtabla_facturas.getSelectedRow();
            if (fila == -1) {
                JOptionPane.showMessageDialog(null, "Seleccione un registro");
            } else {
                int dialogButton = JOptionPane.YES_NO_OPTION;
                int dialogResult = JOptionPane.showConfirmDialog(null, "¿Desea restaurar esta orden?\n"
                        + "TAMBIEN SE RESTAURARAN LAS SALIDAS DE LOS PRODUCTOS ASOCIADAS A ESTA ORDEN", "Alerta", dialogButton, 2);
                if (dialogResult == JOptionPane.YES_OPTION) {
                    try {
                        DefaultTableModel modelo = (DefaultTableModel) jtabla_facturas.getModel();
                        String id = (String) jtabla_facturas.getValueAt(fila, 0);
                        int idOrden = Integer.parseInt(id);

                        // ════════════════════════════════════════════════════════════
                        // INTEGRACIÓN STOCK: Re-aplicar stock al restablecer
                        // ════════════════════════════════════════════════════════════
                        reaplicarStockOrdenRestablecida(idOrden);

                        // Marcar como activo (no anulado)
                        DBfacturas_cabeceras.ActualizaAnulado(id, 1);

                        // Quitar de la tabla de anuladas
                        for (int i = 0; i < modelo.getRowCount(); i++) {
                            if (modelo.getValueAt(i, 0).equals(id)) {
                                modelo.removeRow(i);
                                break;
                            }
                        }
                    } catch (Exception e) {
                        e.printStackTrace();
                    }
                }
            }
        }
    }//GEN-LAST:event_btn_restablecerActionPerformed
    private void reaplicarStockOrdenRestablecida(int idOrden) {
        DBstock_productos dbStock = new DBstock_productos();

        // Obtener bodega y tipo de la orden
        int idBodega = 1;
        String tipoOrden = "Salida";
        String sqlCabecera = "SELECT id_bodega, tipo_factura FROM facturas_cabeceras WHERE id = " + idOrden;
        ResultSet rsCabecera = DB_consultas_R_D.getTabla(sqlCabecera);
        try {
            if (rsCabecera.next()) {
                idBodega = rsCabecera.getInt("id_bodega");
                tipoOrden = rsCabecera.getString("tipo_factura");
            }
            rsCabecera.close();
        } catch (SQLException e) {
            System.out.println("Error obteniendo cabecera: " + e);
        }

        // Obtener detalles y re-aplicar cada producto
        String sql = "SELECT id_producto, cantidad, id_factura FROM facturas_detalles WHERE id_cabecera = " + idOrden;
        ResultSet rs = DB_consultas_R_D.getTabla(sql);
        try {
            while (rs.next()) {
                int idProducto = rs.getInt("id_producto");
                double cantidad = rs.getDouble("cantidad");
                int idFacturaRef = rs.getInt("id_factura");

                if (idFacturaRef == 0) {
                    // Orden normal: compromete pendientes
                    dbStock.orden(
                            idProducto,
                            idBodega,
                            frm_main.id_user,
                            cantidad,
                            idOrden,
                            "Restablecimiento orden - " + tipoOrden
                    );
                } else {
                    // Orden referenciada: suma cantidad Y compromete pendientes
                    dbStock.ordenReferenciada(
                            idProducto,
                            idBodega,
                            frm_main.id_user,
                            cantidad,
                            idOrden,
                            "Restablecimiento orden ref. - Factura WO: " + idFacturaRef
                    );
                }
            }
            rs.close();
        } catch (SQLException e) {
            System.out.println("Error reaplicando stock orden restablecida: " + e);
        }
    }
