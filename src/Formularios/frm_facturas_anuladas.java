    public static void actualizar(String tipo) {
        try {
            for (int i = 0; i < jtabla_facturas.getRowCount(); i++) {
                modelo_facturas.removeRow(i);
                i -= 1;
            }
        } catch (Exception m) {
        }
        String consulta = "with pendientes as (\n"
                + "	with fac_detalle as (\n"
                + "		select fd.id_cabecera, sum(cantidad) as cantidad\n"
                + "		from facturas_detalles fd\n"
                + "		group by fd.id_cabecera\n"
                + "		order by fd.id_cabecera\n"
                + "	),\n"
                + "	entregas as (\n"
                + "		select e.id_factura, coalesce(sum(e.cantidad),0) as cantidad\n"
                + "		from entregas_productos e\n"
                + "		group by  e.id_factura\n"
                + "		order by e.id_factura\n"
                + "	)\n"
                + "	select fd.id_cabecera, coalesce((fd.cantidad-coalesce(sum(e.cantidad),0)),0) as pendiente \n"
                + "	from fac_detalle fd left join entregas e on fd.id_cabecera=e.id_factura\n"
                + "	group by fd.id_cabecera,fd.cantidad,e.cantidad\n"
                + "	order by fd.id_cabecera\n"
                + ")\n"
                + "\n"
                + "select fc.id, fc.codigo, c.nombre as cliente, fc.fecha, fc.tipo_factura, p.pendiente\n"
                + "from facturas_cabeceras fc left join pendientes p on fc.id=p.id_cabecera, contactos c\n"
                + "where fc.anulado=0 and fc.id_contacto=c.id;";

        ResultSet rs = DB_consultas_R_D.getTabla(consulta);

        modelo_facturas.setColumnIdentifiers(new Object[]{"id", "# Factura", "Nombre cliente", "Fecha", "Tipo orden", "Estado"});
        try {
            while (rs.next()) {
                // añade los resultado a al modelo de tabla
                String estado = "";
                if (rs.getDouble("pendiente") > 0) {
                    estado = "Pendiente";
                } else {
                    estado = "Entregado";
                }
                modelo_facturas.addRow(new Object[]{rs.getString("id"), rs.getString("codigo"), rs.getString("cliente"), rs.getString("fecha"), rs.getString("tipo_factura"), estado});
            }
            rs.close();
            // asigna el modelo a la tabla
            jtabla_facturas.setModel(modelo_facturas);
            TamanosTablaAbonos();
        } catch (Exception e) {
            System.out.println("Error consutando frm_facturas: " + e);
        }
    }

