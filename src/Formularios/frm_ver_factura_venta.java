    private void btn_verFactura1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_verFactura1ActionPerformed
        ArrayList<ProductoImprimir> productos = new ArrayList<ProductoImprimir>();
        for (int i = 0; i < jtabla_productos.getRowCount(); i++) {
            ProductoImprimir prod = new ProductoImprimir();

            prod.setNombre("" + jtabla_productos.getValueAt(i, 2).toString());
            prod.setCantidad("" + jtabla_productos.getValueAt(i, 3));
            prod.setPunitario("" + jtabla_productos.getValueAt(i, 4));
            prod.setPtotal("" + jtabla_productos.getValueAt(i, 5));
            productos.add(prod);
        }
        int dia, mes, ano;

        String fecha = lbl_fecha.getText();
        Contactos cliente = new Contactos();
        cliente = cliente.TraerContacto(lbl_id_cliente.getText());
        double desc = 0;
        String credicontado = lbl_tipo_pago.getText();
        ImprimirTermica80MM imprimir = new ImprimirTermica80MM(fecha, lbl_numerofactura.getText(), lbl_total.getText(), cliente, productos, lbl_user.getText(), lbl_hora.getText(), credicontado);
        try {
            imprimir.imprime();
        } catch (PrinterException ex) {
            Logger.getLogger(frm_ver_orden.class.getName()).log(Level.SEVERE, null, ex);
        }


    }//GEN-LAST:event_btn_verFactura1ActionPerformed


