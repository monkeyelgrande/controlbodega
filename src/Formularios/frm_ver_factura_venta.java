    private void btn_editar_serialActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_editar_serialActionPerformed
        if (DB_consultas_R_D.validar_admin()) {

            if (edit_codigo) {
                if (DB_consultas_R_D.validar_admin()) {
                    txt_codigo.setEditable(true);
                    edit_codigo = false;
                }
            } else {

                Connection con = DB_consultas_R_D.getConexion();
                PreparedStatement psql = null;

                String sql = "update facturas_cabeceras set "
                        + "codigo='" + txt_codigo.getText() + "' "
                        + "where id=" + lbl_numerofactura.getText();

                try {

                    psql = con.prepareStatement(sql);
                    psql.executeUpdate();
                    psql.close();
                    con.close();

                    txt_codigo.setEditable(false);

                } catch (Exception e) {
                    System.out.println(e);
                }

            }
        }
    }//GEN-LAST:event_btn_editar_serialActionPerformed

    public static void calcular_total() {

        try {

            double total_costo = 0;

            for (int i = 0; i < modelo_productos.getRowCount(); i++) {
                double precio = Double.parseDouble(metodos.EliminaCaracteres(modelo_productos.getValueAt(i, 5).toString(), "."));
                total_costo += precio;
            }

            lbl_total.setText(metodos.formateador_dinero().format(total_costo));

        } catch (Exception e) {
            JOptionPane.showMessageDialog(jtabla_productos, "Por favor verifique los precios y cantidades en la tabla");
        }

    }
