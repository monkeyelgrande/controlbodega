    private void btn_verActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_verActionPerformed
        frm_ver_recorte frm = new frm_ver_recorte();

        int fila = jtabla_facturas.getSelectedRow();
        String id = (String) jtabla_facturas.getValueAt(fila, 0);

        String consulta = "select rd.id as id_f, rd.fecha, rd.hora, rd.fecha_entrega, rd.estado, rd.hora_entrega, rd.codigo, \n"
                + "rd.observacion, c.id as id_c, c.cedula, c.nombre, c.direccion, c.contacto, u.user_name, p.descripcion\n"
                + "from recortes_detalle rd, recortes_cabecera rc, contactos c, users u, productos p\n"
                + "where rd.id_user=u.id and rd.id_contacto=c.id and rd.id_cabecera=rc.id and rc.id_producto=p.id and rd.id=" + id;

//        System.out.println(consulta);
        ResultSet rs = DB_consultas_R_D.getTabla(consulta);
        try {
            while (rs.next()) {
                frm.lbl_id_recorte_detalle.setText(rs.getString("id_f"));
                frm.lbl_fecha.setText(rs.getString("fecha"));
                frm.lbl_hora.setText(rs.getString("hora"));
                frm.lbl_fecha_entrega.setText(rs.getString("fecha_entrega"));
                frm.lbl_hora_entrega.setText(rs.getString("hora_entrega"));
                frm.lbl_id_cliente.setText(rs.getString("id_c"));
                frm.lbl_nombre_cliente.setText(rs.getString("nombre"));
                frm.lbl_cedula_cliente.setText(rs.getString("cedula"));
                frm.lbl_direccion_cliente.setText(rs.getString("direccion"));
                frm.lbl_celular_cliente.setText(rs.getString("contacto"));
                frm.lbl_user.setText(rs.getString("user_name"));
                frm.txt_codigo.setText(rs.getString("codigo"));
                frm.txt_observaciones.setText(rs.getString("observacion"));
                frm.lbl_decripcion_producto.setText(rs.getString("descripcion"));
                frm.lbl_estado.setText(rs.getString("estado"));
            }
            rs.close();

        } catch (SQLException ex) {
            System.out.println(ex);
        }
        frm.btn_llenar.requestFocus();
        frm.show();

    }//GEN-LAST:event_btn_verActionPerformed

