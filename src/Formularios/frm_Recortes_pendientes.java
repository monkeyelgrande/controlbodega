    public static void actualizar(String tipo) {
        try {
            for (int i = 0; i < modelo_facturas.getRowCount(); i++) {
                modelo_facturas.removeRow(i);
                i -= 1;
            }
        } catch (Exception m) {
        }
        ResultSet rs = null;

        String consulta = "";

        if (tipo.equals("pendientes")) {
            consulta = "select rd.id, rd.codigo, c.nombre, p.descripcion, rd.cantidad, rd.estado \n"
                    + "from recortes_detalle rd inner join contactos c on rd.id_contacto=c.id inner join recortes_cabecera rc on rd.id_cabecera=rc.id inner join productos p on rc.id_producto=p.id \n"
                    + "where estado=0 order by id;";

        } else {
            consulta = "select rd.id, rd.codigo, c.nombre, p.descripcion, rd.cantidad, rd.estado \n"
                    + "from recortes_detalle rd inner join contactos c on rd.id_contacto=c.id inner join recortes_cabecera rc on rd.id_cabecera=rc.id inner join productos p on rc.id_producto=p.id \n"
                    + "order by id;";

        }
//        System.out.println(consulta);
        rs = DB_consultas_R_D.getTabla(consulta);
        modelo_facturas.setColumnIdentifiers(new Object[]{"id", "# Factura", "Nombre cliente", "Producto", "Cantidad", "Estado"});
        try {
            while (rs.next()) {
                // añade los resultado a al modelo de tabla
                String estado = "";
                if (rs.getInt("estado") > 0) {
                    estado = "Entregado";
                } else {
                    estado = "Pendiente";
                }
                modelo_facturas.addRow(new Object[]{rs.getString("id"), rs.getString("codigo"), rs.getString("nombre"),
                    rs.getString("descripcion"), rs.getDouble("cantidad"), estado});
            }
            rs.close();
            // asigna el modelo a la tabla
            jtabla_facturas.setModel(modelo_facturas);
            TamanosTablaAbonos();
        } catch (Exception e) {
            System.out.println("Error consutando frm_facturas: " + e);
        }
    }

