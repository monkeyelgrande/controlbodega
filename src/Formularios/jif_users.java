    public void filtro() {
        int columnaABuscar = 0;
        switch (comboFiltro.getSelectedItem() + "") {
            case "Nombre":
                columnaABuscar = 1;
                break;
            case "Cedula":
                columnaABuscar = 2;
                break;
            case "Direccion":
                columnaABuscar = 3;
                break;
            case "Celular":
                columnaABuscar = 4;
                break;
            case "Telefono":
                columnaABuscar = 5;
                break;
            case "Descuento":
                columnaABuscar = 6;
                break;
            case "Email":
                columnaABuscar = 7;
                break;
        }
        trsFiltro.setRowFilter(RowFilter.regexFilter(txt_Filtro.getText(), columnaABuscar));
    }
