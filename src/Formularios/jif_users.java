    public void mostrar() {

        ResultSet rs = DB_consultas_R_D.getTabla("select u.id,nombre,user_name,telefono,estado,p.perfil as perfil from users u, perfiles p where p.id=u.id_perfil order by u.id");
        modelo.setColumnIdentifiers(new Object[]{"id", "Nombre", "Nombre de usuario", "Celular", "Estado", "Perfil"});
        try {
            while (rs.next()) {
                // añade los resultado a al modelo de tabla
                modelo.addRow(new Object[]{rs.getString("id"), rs.getString("nombre"), rs.getString("user_name"), rs.getString("telefono"),
                    rs.getString("estado"), rs.getString("perfil")});
            }
            rs.close();
            // asigna el modelo a la tabla
            jtabla_clientes.setModel(modelo);
        } catch (Exception e) {
            System.out.println(e);
        }
    }
    private void btn_eliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_eliminarActionPerformed

        if (DB_consultas_R_D.validar_admin()) {
            int fila = jtabla_clientes.getSelectedRow();
            if (fila == -1) {
                JOptionPane.showMessageDialog(null, "Seleccione un registro");
            } else {
                int dialogButton = JOptionPane.YES_NO_OPTION;
                int dialogResult = JOptionPane.showConfirmDialog(null, "Desea eliminar este usuario?", "Alerta", dialogButton);
                if (dialogResult == JOptionPane.YES_OPTION) {
                    try {
                        DefaultTableModel modelo = (DefaultTableModel) jtabla_clientes.getModel();
                        String id = (String) jtabla_clientes.getValueAt(fila, 0);//suponiendo que el id lo muestras en la primera columna
                        DB_consultas_R_D.eliminar("users", id);
                        for (int i = 0; i < modelo.getRowCount(); i++) {
                            if (modelo.getValueAt(i, 0).equals(id)) {
                                modelo.removeRow(i);
                                break;
                            }
                        }
                    } catch (Exception e) {
                        e.printStackTrace();
                    }
                }
            }
        }
    }//GEN-LAST:event_btn_eliminarActionPerformed
    DefaultTableModel modelo = new DefaultTableModel() {
        @Override
        public boolean isCellEditable(int fila, int columna) {
            return false; //Con esto conseguimos que la tabla no se pueda editar
        }
    };
    private void btn_editarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_editarActionPerformed

        if (DB_consultas_R_D.validar_admin()) {
            int fila = jtabla_clientes.getSelectedRow();
            if (fila < 0) {
                JOptionPane.showMessageDialog(this, "Seleccione un registro");
            } else {
                String id = (String) jtabla_clientes.getValueAt(fila, 0);
                String consulta = "select u.id, u.nombre, u.password, u.user_name, u.direccion, u.telefono, u.telefono2, u.estado, u.email, "
                        + "       p.perfil as perfil, b.nombre as bodega, "
                        + "       u.imprime_ordenes, u.nombre_impresora, u.imp_ticket_bodega_asignada, u.barra_notificaciones, u.panel_notificaciones, u.aprueba_compras "
                        + "from users u "
                        + "left join perfiles p on p.id = u.id_perfil "
                        + "left join bodegas b on b.id = u.id_bodega "
                        + "where u.id = " + id;
//                System.out.println(consulta);
                ResultSet rs = DB_consultas_R_D.getTabla(consulta);
                jif_crear_user frm = new jif_crear_user();

                try {
                    while (rs.next()) {
                        jif_crear_user.txt_id.setText(rs.getString("id"));
                        jif_crear_user.txt_nombre.setText(rs.getString("nombre"));
//                    jif_crear_user.txt_password.setText(rs.getString("password"));
                        jif_crear_user.txt_user_name.setText(rs.getString("user_name"));
                        jif_crear_user.txt_direccion.setText(rs.getString("direccion"));
                        jif_crear_user.txt_contacto.setText(rs.getString("telefono"));
                        jif_crear_user.txt_contacto2.setText(rs.getString("telefono2"));
                        jif_crear_user.txt_email.setText(rs.getString("email"));
                        jif_crear_user.jbox_estado.setSelectedItem(rs.getString("estado"));

                        // Seleccionar perfil comparando por nombre (el combo tiene objetos Perfiles)
                        String perfilStr = rs.getString("perfil");
                        for (int i = 0; i < jif_crear_user.jbox_perfil.getItemCount(); i++) {
                            if (jif_crear_user.jbox_perfil.getItemAt(i).toString().equals(perfilStr)) {
                                jif_crear_user.jbox_perfil.setSelectedIndex(i);
                                break;
                            }
                        }

                        // Seleccionar bodega comparando por nombre (el combo tiene objetos Bodegas)
                        String bodegaStr = rs.getString("bodega");
                        for (int i = 0; i < jif_crear_user.jbox_bodega.getItemCount(); i++) {
                            if (jif_crear_user.jbox_bodega.getItemAt(i).toString().equals(bodegaStr)) {
                                jif_crear_user.jbox_bodega.setSelectedIndex(i);
                                break;
                            }
                        }

                        // Auto-impresión
                        boolean imprime = rs.getBoolean("imprime_ordenes");
                        String nombreImp = rs.getString("nombre_impresora");
                        boolean impTicketBodega = rs.getBoolean("imp_ticket_bodega_asignada");
                        if (jif_crear_user.chk_imprime_ordenes != null) {
                            jif_crear_user.chk_imprime_ordenes.setSelected(imprime);
                            jif_crear_user.cmb_impresora.setEnabled(imprime);
                            if (nombreImp != null) {
                                jif_crear_user.cmb_impresora.setSelectedItem(nombreImp);
                            }
                        }
                        if (jif_crear_user.chk_imp_ticket_bodega != null) {
                            jif_crear_user.chk_imp_ticket_bodega.setSelected(impTicketBodega);
                        }

                        boolean barraNotif = rs.getBoolean("barra_notificaciones");
                        if (jif_crear_user.chk_barra_notificaciones != null) {
                            jif_crear_user.chk_barra_notificaciones.setSelected(barraNotif);
                        }

                        boolean panelNotif = rs.getBoolean("panel_notificaciones");
                        if (jif_crear_user.chk_panel_notificaciones != null) {
                            jif_crear_user.chk_panel_notificaciones.setSelected(panelNotif);
                        }

                        boolean apruebaCompras = rs.getBoolean("aprueba_compras");
                        if (jif_crear_user.chk_aprueba_compras != null) {
                            jif_crear_user.chk_aprueba_compras.setSelected(apruebaCompras);
                        }

                        // Roles del módulo Precios (pueden ser varios)
                        if (jif_crear_user.chk_rol_almacenista != null) {
                            java.util.List<Integer> rolesPre
                                    = conexiondb.DBpermisos.rolesPrecios(Integer.parseInt(id));
                            jif_crear_user.chk_rol_almacenista.setSelected(rolesPre.contains(2));
                            jif_crear_user.chk_rol_contable.setSelected(rolesPre.contains(3));
                            jif_crear_user.chk_rol_precios.setSelected(rolesPre.contains(4));
                        }

                    }
                    rs.close();
                    if (flag) {
                        jif_crear_user.txt_id.setEnabled(false);
                        jif_crear_user.txt_nombre.setEnabled(false);
                        jif_crear_user.txt_user_name.setEnabled(false);
                        jif_crear_user.txt_direccion.setEnabled(false);
                        jif_crear_user.txt_contacto.setEnabled(false);
                        jif_crear_user.txt_contacto2.setEnabled(false);
                        jif_crear_user.txt_email.setEnabled(false);
                        jif_crear_user.txt_password.setEnabled(false);
                        jif_crear_user.jbox_estado.setEnabled(false);
                        jif_crear_user.jbox_perfil.setEnabled(false);
                        jif_crear_user.btn_guardar.setEnabled(false);
                        jif_crear_user.btn_limpiar.setEnabled(false);
                        jif_crear_user.chk_cerrar.setEnabled(false);
                        jif_crear_user.btn_editar.setVisible(true);
                    }
                    flag = false;

                } catch (SQLException ex) {
                    Logger.getLogger(frm_contactos.class.getName()).log(Level.SEVERE, null, ex);
                }
                frm.show();

            }
        }
    }//GEN-LAST:event_btn_editarActionPerformed

