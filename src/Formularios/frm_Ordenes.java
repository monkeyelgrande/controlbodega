    private void reversarStockOrdenAnulada(int idOrden) {
        DBstock_productos dbStock = new DBstock_productos();

        // Obtener bodega de la orden
        int idBodega = 1;
        String sqlBodega = "SELECT id_bodega FROM facturas_cabeceras WHERE id = " + idOrden;
        ResultSet rsBodega = DB_consultas_R_D.getTabla(sqlBodega);
        try {
            if (rsBodega.next()) {
                idBodega = rsBodega.getInt("id_bodega");
            }
            rsBodega.close();
        } catch (SQLException e) {
            System.out.println("Error obteniendo bodega: " + e);
        }

        // Obtener detalles y reversar cada producto
        String sql = "SELECT id_producto, cantidad, id_factura FROM facturas_detalles WHERE id_cabecera = " + idOrden;
        ResultSet rs = DB_consultas_R_D.getTabla(sql);
        try {
            while (rs.next()) {
                int idProducto = rs.getInt("id_producto");
                double cantidad = rs.getDouble("cantidad");
                int idFacturaRef = rs.getInt("id_factura");

                if (idFacturaRef == 0) {
                    // Orden normal: solo liberar pendientes
                    dbStock.anulacionOrden(
                            idProducto,
                            idBodega,
                            frm_main.id_user,
                            cantidad,
                            idOrden,
                            "Anulación de orden"
                    );
                } else {
                    // Orden referenciada: revertir cantidad Y pendientes
                    dbStock.anulacionOrdenReferenciada(
                            idProducto,
                            idBodega,
                            frm_main.id_user,
                            cantidad,
                            idOrden,
                            "Anulación orden ref. - Factura WO: " + idFacturaRef
                    );
                }
            }
            rs.close();
        } catch (SQLException e) {
            System.out.println("Error reversando stock orden anulada: " + e);
        }
    }
