    private void btn_editarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_editarActionPerformed
        boolean autorizado = false;
        if (frm_main.perfil == 3) { // VENDEDOR: puede editar solo si no ha impreso
            int fila_sel = jtabla_facturas.getSelectedRow();
            if (fila_sel < 0) {
                JOptionPane.showMessageDialog(null, "Seleccione un registro");
                return;
            }
            String id_orden_sel = (String) jtabla_facturas.getValueAt(fila_sel, 0);
            try {
                Connection con = DB_consultas_R_D.getConexion();
                PreparedStatement ps = con.prepareStatement(
                        "SELECT COALESCE(impreso_vendedor, 0) FROM facturas_cabeceras WHERE id = ?");
                ps.setInt(1, Integer.parseInt(id_orden_sel));
                ResultSet rsi = ps.executeQuery();
                int impreso = 0;
                if (rsi.next()) {
                    impreso = rsi.getInt(1);
                }
                rsi.close();
                ps.close();
                con.close();
                if (impreso == 1) {
                    JOptionPane.showMessageDialog(this,
                            "Esta orden ya fue impresa. No puede modificarla.");
                    return;
                }
                autorizado = true;
            } catch (Exception ex) {
                JOptionPane.showMessageDialog(this, "Error validando impresion: " + ex.getMessage());
                return;
            }
        } else {
            autorizado = DB_consultas_R_D.validar_admin();
        }
        if (autorizado) {
            DecimalFormatSymbols sim = new DecimalFormatSymbols();
            sim.setDecimalSeparator('.');
            DecimalFormat formatea = new DecimalFormat("###,###.##", sim);
            columnModel = frm_editar_orden.jtabla_Ventas.getColumnModel();

            int fila = jtabla_facturas.getSelectedRow();
            if (fila < 0) {
                JOptionPane.showMessageDialog(null, "Seleccione un registro");
            } else {
                String id_orden = (String) jtabla_facturas.getValueAt(fila, 0);

                if (DB_consultas_R_D.consutla_entregas(id_orden) > 0) {
                    JOptionPane.showMessageDialog(this, "Esta orden ya tiene entregas realziadas\nNO puede editarla hasta eliminar estas entregas priemero\nDepues debe volver a crear estas entregas");
                } else {

                    ResultSet rs = DB_consultas_R_D.getTabla(
                            "SELECT "
                            + "   f.id AS id_f, "
                            + "   f.fecha, "
                            + "   f.hora, "
                            + "   c.id AS id_c, "
                            + "   c.cedula, "
                            + "   c.nombre, "
                            + "   c.direccion, "
                            + "   c.contacto, "
                            + "   f.tipo_factura, "
                            + "   u.user_name, "
                            + "   f.codigo, "
                            + "   f.observacion, "
                            + "   b.id as id_bodega, "
                            + "   b.nombre AS bodega "
                            + "FROM facturas_cabeceras f "
                            + "JOIN contactos c ON f.id_contacto = c.id "
                            + "JOIN users u ON f.id_user = u.id "
                            + "LEFT JOIN bodegas b ON b.id = f.id_bodega "
                            + "WHERE f.id = " + id_orden
                    );
                    try {
                        while (rs.next()) {
                            frm_editar_orden.lbl_numerofactura.setText(rs.getString("id_f"));
                            frm_editar_orden.lbl_id_cliente.setText(rs.getString("id_c"));
                            frm_editar_orden.jbox_cliente.setSelectedItem(rs.getString("nombre"));
                            frm_editar_orden.txt_codigo.setText(rs.getString("codigo"));
                            frm_editar_orden.txt_observaciones.setText(rs.getString("observacion"));
                            String tipo_salida = rs.getString("tipo_factura");
                            if (tipo_salida.equals("Salida")) {
                                frm_editar_orden.rb_salida.setSelected(true);
                            } else if (tipo_salida.equals("Eliminación")) {
                                frm_editar_orden.rb_eliminacion.setSelected(true);
                            } else {
                                frm_editar_orden.rb_prestamo.setSelected(true);
                            }
                            frm_editar_orden.jbox_bodega.setSelectedItem(rs.getString("bodega"));
                            frm_editar_orden.id_bodega = rs.getInt("id_bodega");
                        }
                        rs.close();

                    } catch (SQLException ex) {
                        Logger.getLogger(frm_ver_orden.class.getName()).log(Level.SEVERE, null, ex);
                    }

                    rs = DB_consultas_R_D.getTabla("select p.id, p.codigo_barras, p.descripcion, f.cantidad, f.id_factura "
                            + "from facturas_detalles f, productos p where f.id_producto=p.id and id_cabecera=" + id_orden);

                    frm_editar_orden.modelo.setRowCount(0);
                    frm_editar_orden.TamanosTablaVentas();

                    frm_editar_orden.modelo.setColumnIdentifiers(new Object[]{"ID", "CODIGO", "DESCRIPCIÓN", "CANTIDAD", "R"});
                    try {
                        while (rs.next()) {
                            frm_editar_orden.modelo.addRow(new Object[]{rs.getString("id"), rs.getString("codigo_barras"), rs.getString("descripcion"),
                                metodos.formateador_x_decimal(3).format(rs.getDouble("cantidad")), rs.getString("id_factura")
                            });
                        }
                        rs.close();
                        frm_editar_orden.jtabla_Ventas.setModel(frm_editar_orden.modelo);
                        frm_editar_orden.TamanosTablaVentas();
                    } catch (SQLException ex) {
                        Logger.getLogger(frm_ver_orden.class.getName()).log(Level.SEVERE, null, ex);
                    }
                    frm_editar_orden.show(true);
                }
            }
        }

    }//GEN-LAST:event_btn_editarActionPerformed
