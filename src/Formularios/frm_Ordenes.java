    private void btn_eliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_eliminarActionPerformed
        if (DB_consultas_R_D.validar_admin()) {
            int fila = jtabla_facturas.getSelectedRow();
            if (fila == -1) {
                JOptionPane.showMessageDialog(null, "Seleccione un registro");
            } else {
                try {
                    String id = (String) jtabla_facturas.getValueAt(fila, 0);
                    int idOrden = Integer.parseInt(id);

                    // ════════════════════════════════════════════════════════════
                    // VALIDACIÓN: No permitir anular si tiene entregas asociadas
                    // ════════════════════════════════════════════════════════════
                    if (tieneEntregasAsociadas(idOrden)) {
                        JOptionPane.showMessageDialog(null,
                                "No se puede anular esta orden porque ya tiene entregas registradas.\n\n"
                                + "Debe eliminar primero las entregas asociadas antes de anular la orden.",
                                "Operación no permitida",
                                JOptionPane.WARNING_MESSAGE);
                        return;
                    }

                    int dialogButton = JOptionPane.YES_NO_OPTION;
                    int dialogResult = JOptionPane.showConfirmDialog(null,
                            "¿Desea anular esta orden?\n"
                            + "TAMBIEN SE ANULARAN LAS SALIDAS DE LOS PRODUCTOS ASOCIADAS A ESTA ORDEN",
                            "Alerta", dialogButton, 2);

                    if (dialogResult == JOptionPane.YES_OPTION) {
                        DefaultTableModel modelo = (DefaultTableModel) jtabla_facturas.getModel();

                        // ════════════════════════════════════════════════════════════
                        // INTEGRACIÓN STOCK: Reversar stock antes de anular
                        // ════════════════════════════════════════════════════════════
                        reversarStockOrdenAnulada(idOrden);

                        // Marcar como anulado
                        DBfacturas_cabeceras.ActualizaAnulado(id, 0);

                        // Quitar de la tabla visual
                        for (int i = 0; i < modelo.getRowCount(); i++) {
                            if (modelo.getValueAt(i, 0).equals(id)) {
                                modelo.removeRow(i);
                                break;
                            }
                        }
                    }
                } catch (Exception e) {
                    e.printStackTrace();
                }
            }
        }
    }//GEN-LAST:event_btn_eliminarActionPerformed
    private boolean tieneEntregasAsociadas(int idOrden) {
        String sql = "SELECT COUNT(*) AS total FROM entregas_productos_cabecera WHERE id_factura = " + idOrden;
        ResultSet rs = DB_consultas_R_D.getTabla(sql);
        try {
            if (rs.next()) {
                int total = rs.getInt("total");
                rs.close();
                return total > 0;
            }
            rs.close();
        } catch (SQLException e) {
            System.out.println("Error verificando entregas: " + e);
        }
        return false;
    }
