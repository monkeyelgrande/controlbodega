    public static void actualizar(String tipo) {
        modelo_facturas.setRowCount(0);
        modelo_facturas.setColumnIdentifiers(new Object[]{"id", "# Factura", "Nombre cliente", "Fecha", "Tipo orden", "Estado", "Bodega"});
        String SQL_FACTURAS = "WITH\n"
                + "  detalles AS (\n"
                + "    SELECT \n"
                + "      id_cabecera, \n"
                + "      SUM(cantidad) AS total_detalles\n"
                + "    FROM facturas_detalles\n"
                + "    GROUP BY id_cabecera\n"
                + "  ),\n"
                + "  entregas AS (\n"
                + "    SELECT \n"
                + "      id_factura AS id_cabecera, \n"
                + "      SUM(cantidad) AS total_entregas\n"
                + "    FROM entregas_productos\n"
                + "    GROUP BY id_factura\n"
                + "  )\n"
                + "SELECT\n"
                + "  fc.id,\n"
                + "  fc.codigo,\n"
                + "  c.nombre      AS cliente,\n"
                + "  fc.fecha,\n"
                + "  fc.tipo_factura,\n"
                + "  GREATEST(\n"
                + "    COALESCE(d.total_detalles, 0)\n"
                + "    - COALESCE(e.total_entregas,  0),\n"
                + "    0\n"
                + "  ) AS pendiente,\n"
                + "  b.nombre AS bodega\n"
                + "FROM facturas_cabeceras fc\n"
                + "JOIN contactos c\n"
                + "  ON fc.id_contacto = c.id\n"
                + "LEFT JOIN detalles d\n"
                + "  ON d.id_cabecera = fc.id\n"
                + "LEFT JOIN entregas e\n"
                + "  ON e.id_cabecera = fc.id\n"
                + "LEFT JOIN bodegas b\n"
                + "  ON b.id = fc.id_bodega\n"
                + "WHERE\n"
                + "  fc.anulado = 1\n"
                + "  AND fc.tipo_factura <> 'Venta'\n"
                + "ORDER BY fc.id desc;";
//        System.out.println(SQL_FACTURAS);

        try (ResultSet rs = DB_consultas_R_D.getTabla(SQL_FACTURAS)) {

            while (rs.next()) {
                double pendiente = rs.getDouble("pendiente");

                // 3. Si el filtro es "pendientes", saltarse las que estén en 0
                if ("pendientes".equalsIgnoreCase(tipo) && pendiente == 0) {
                    continue;
                }
                if (frm_main.lbl_perfil.getText().equals("bodeguero") && !frm_main.lbl_bodega_user.getText().equals(rs.getString("bodega"))) {
                    continue;
                }

                String estado = (pendiente != 0) ? "Pendiente" : "Entregado";

                modelo_facturas.addRow(new Object[]{
                    rs.getString("id"),
                    rs.getString("codigo"),
                    rs.getString("cliente"),
                    rs.getString("fecha"),
                    rs.getString("tipo_factura"),
                    estado,
                    rs.getString("bodega") // ← NUEVA COLUMNA AL FINAL
                });
            }

            // 4. Asignar modelo y ajustar columnas
            jtabla_facturas.setModel(modelo_facturas);
            TamanosTablaAbonos();

        } catch (Exception e) {
            System.out.println("Error consultando frm_facturas: " + e.getMessage());
        }
    }

