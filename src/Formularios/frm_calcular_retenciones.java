        nuevo_19 = total_19 + (total_19 * 0.0214592);
        nuevo_5 = total_5 + (total_5 * 0.02439021);
        nuevo_0 = total_0 + (total_0 * 0.02564);

        iva_19 = nuevo_19 * 0.19;
        iva_5 = nuevo_5 * 0.05;

        subtotal = nuevo_19 + nuevo_5 + nuevo_0 + iva_19 + iva_5;

        retefuente = (nuevo_19 + nuevo_5 + nuevo_0) * 0.025;

        total_pagar = subtotal - retefuente;

        diferencia_19 = nuevo_19 - total_19;
        diferencia_5 = nuevo_5 - total_5;
        diferencia_0 = nuevo_0 - total_0;

        lbl_Nuevo_19.setText(metodos.formateador_dinero().format(nuevo_19));
