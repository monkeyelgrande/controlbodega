        txt_Pagar.setText(metodos.formateador_dinero().format(total_pagar));

        lbl_Iva_19.setText(metodos.formateador_dinero().format(iva_19));
        lbl_Iva_5.setText(metodos.formateador_dinero().format(iva_5));

        lbl_Diferencia_19.setText(metodos.formateador_dinero().format(diferencia_19));
