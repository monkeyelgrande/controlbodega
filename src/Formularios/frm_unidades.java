    private void btn_editarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_editarActionPerformed
        int fila = jtabla.getSelectedRow();
        if (fila < 0) {
            JOptionPane.showMessageDialog(this, "Seleccione un registro");
        } else {
            String id = (String) jtabla.getValueAt(fila, 0);
            ResultSet rs = DB_consultas_R_D.getTabla("select * from unidades_medidas where id =" + id);
            jif_crear_unidades_medida frm = new jif_crear_unidades_medida();
            try {
                while (rs.next()) {
                    jif_crear_unidades_medida.txt_id.setText(rs.getString("id"));
                    jif_crear_unidades_medida.txt_nombre.setText(rs.getString("nombre"));
                }
                rs.close();

            } catch (SQLException ex) {
                Logger.getLogger(frm_contactos.class.getName()).log(Level.SEVERE, null, ex);
            }
            if (ver) {
                frm.txt_nombre.setEnabled(false);
                frm.btn_guardar.setEnabled(false);
                frm.btn_limpiar.setEnabled(false);
                frm.chk_cerrar.setEnabled(false);
                frm.btn_editar.setVisible(true);
            }
            ver = false;
            frm.show();
            jif_crear_unidades_medida.txt_nombre.requestFocus();

        }
    }//GEN-LAST:event_btn_editarActionPerformed

