    private void btn_editarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_editarActionPerformed
        jd_orden_de_recorte frm = new jd_orden_de_recorte(null, closable);

        int fila = jtabla_productos.getSelectedRow();
        if (fila < 0) {
            JOptionPane.showMessageDialog(this, "Seleccione un registro");
        } else {
            String id = "" + jtabla_productos.getValueAt(fila, 0);
            ResultSet rs;
            String consulta = "select rc.id, p.descripcion, p.id as id_producto, rc.cantidad, coalesce(sum(rd.cantidad),0) as entregado, (rc.cantidad-coalesce(sum(rd.cantidad),0)) as pendiente\n"
                    + "from recortes_cabecera rc left join recortes_detalle rd on rd.id_cabecera=rc.id, productos p  \n"
                    + "where rc.id_producto=p.id and rc.id=" + id + "\n"
                    + "group by rc.id, p.descripcion, p.id, rc.cantidad";
//            System.out.println(consulta);
            rs = DB_consultas_R_D.getTabla(consulta);
            try {
                while (rs.next()) {
                    jd_orden_de_recorte.lbl_id_recorte.setText(rs.getString("id"));
                    jd_orden_de_recorte.lbl_id_producto.setText(rs.getString("id_producto"));
                    jd_orden_de_recorte.lbl_descripcion_producto.setText(rs.getString("descripcion"));
                    jd_orden_de_recorte.lbl_user.setText(frm_main.lbl_user.getText());
                    jd_orden_de_recorte.lbl_total_producto.setText(metodos.formateador_decimal_punto_para_decimal().format(rs.getDouble("cantidad")));
                    jd_orden_de_recorte.lbl_total_entregado.setText(metodos.formateador_decimal_punto_para_decimal().format(rs.getDouble("entregado")));
                    jd_orden_de_recorte.lbl_total_saldo.setText(metodos.formateador_decimal_punto_para_decimal().format(rs.getDouble("pendiente")));
                }
                rs.close();

            } catch (SQLException ex) {
                Logger.getLogger(frm_Ordenes.class.getName()).log(Level.SEVERE, null, ex);
            }
            try {
                for (int i = 0; i < jd_orden_de_recorte.modelo_ver_entregas.getRowCount(); i++) {
                    jd_orden_de_recorte.modelo_ver_entregas.removeRow(i);
                    i -= 1;
                }
            } catch (Exception e) {
            }
            rs = DB_consultas_R_D.getTabla("select r.*, u.nombre from recortes_detalle r, users u where r.id_user=u.id and id_cabecera=" + id + "");

            jd_orden_de_recorte.modelo_ver_entregas.setColumnIdentifiers(new Object[]{"ID", "Usuario", "Cantidad", "fecha", "Hora"});
            try {
                while (rs.next()) {
                    jd_orden_de_recorte.modelo_ver_entregas.addRow(new Object[]{rs.getString("id"), rs.getString("nombre"), ""
                        + metodos.formateador_decimal_punto_para_decimal().format(rs.getDouble("cantidad")),
                        rs.getDate("fecha"), rs.getString("hora")});
                }
                rs.close();
                jd_orden_de_recorte.jtabla.setModel(jd_orden_de_recorte.modelo_ver_entregas);
                jd_orden_de_recorte.txt_cantidad.requestFocus();
            } catch (SQLException ex) {
                Logger.getLogger(frm_Ordenes.class.getName()).log(Level.SEVERE, null, ex);
            }
            frm.show();
        }

    }//GEN-LAST:event_btn_editarActionPerformed

