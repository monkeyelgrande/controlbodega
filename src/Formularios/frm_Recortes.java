    public void actualizar() {
        boolean actualiza = true;
        try {
            for (int i = 0; i < modelo.getRowCount(); i++) {
                modelo.removeRow(i);
                i -= 1;
            }
        } catch (Exception e) {
        }
        String consulta = "";
        if (actualiza) {
            consulta = "with consulta as (\n"
                    + "	select rc.id, p.codigo_barras, p.descripcion, rc.fecha, rc.cantidad, coalesce(sum(rd.cantidad),0) as entregado, (rc.cantidad-coalesce(sum(rd.cantidad),0)) as saldo\n"
                    + "	from recortes_cabecera rc left join recortes_detalle rd on rd.id_cabecera=rc.id, productos p \n"
                    + "	where rc.id_producto=p.id \n"
                    + "	group by rc.id, p.codigo_barras, p.descripcion, rc.fecha, rc.cantidad\n"
                    + "	order by rc.id, p.codigo_barras, p.descripcion, rc.fecha, rc.cantidad\n"
                    + ")\n"
                    + "select * from consulta";
            actualiza = false;
        } else {
            consulta = "with consulta as (\n"
                    + "	select rc.id, p.codigo_barras, p.descripcion, rc.fecha, rc.cantidad, coalesce(sum(rd.cantidad),0) as entregado, (rc.cantidad-coalesce(sum(rd.cantidad),0)) as saldo\n"
                    + "	from recortes_cabecera rc left join recortes_detalle rd on rd.id_cabecera=rc.id, productos p \n"
                    + "	where rc.id_producto=p.id \n"
                    + "	group by rc.id, p.codigo_barras, p.descripcion, rc.fecha, rc.cantidad\n"
                    + "	order by rc.id, p.codigo_barras, p.descripcion, rc.fecha, rc.cantidad\n"
                    + ")\n"
                    + "select * from consulta where saldo>0";
            actualiza = true;
        }
        ResultSet rs = DB_consultas_R_D.getTabla(consulta);

        modelo.setColumnIdentifiers(new Object[]{"id", "Codigo barras", "Descripción", "cantidad", "Entregado", "Saldo", "fecha"});
        try {
            while (rs.next()) {
                // añade los resultado a al modelo de tabla
                modelo.addRow(new Object[]{rs.getString("id"), rs.getString("codigo_barras"), rs.getString("descripcion"),
                    metodos.formateador_decimal_punto_para_decimal().format(rs.getDouble("cantidad")),
                    metodos.formateador_decimal_punto_para_decimal().format(rs.getDouble("entregado")),
                    metodos.formateador_decimal_punto_para_decimal().format(rs.getDouble("saldo")), (rs.getString("fecha"))});
            }
            rs.close();
            // asigna el modelo a la tabla
            jtabla_productos.setModel(modelo);
            TamanosTablaAbonos();
        } catch (Exception e) {
            System.out.println(e);
        }
    }

    public void cargarFiltros(String consulta, JComboBox jbox) {
        ResultSet rs = DB_consultas_R_D.getTabla(consulta);
        DefaultComboBoxModel modelosmarca = new DefaultComboBoxModel();

        modelosmarca.addElement("");
        try {
            while (rs.next()) {
                modelosmarca.addElement(rs.getString("nombre"));
            }
            rs.close();
            jbox.setModel(modelosmarca);
        } catch (Exception e) {
            System.out.println(e);
        }
        AutoCompleteDecorator.decorate(jbox);
    }

