    public int consultarId(String id) {
        ResultSet rs = DB_consultas_R_D.getTabla("select count(id) as id from clientes where id = " + id + "");
        try {
            while (rs.next()) {
                // añade los resultado a al modelo de tabla
                return Integer.parseInt(rs.getString("id"));
            }
            rs.close();
            // asigna el modelo a la tabla
            jtabla_productos.setModel(modelo);
        } catch (Exception e) {
            System.out.println(e);
            return 0;
        }
        return 0;
    }
    private void btn_eliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_eliminarActionPerformed
        if (DB_consultas_R_D.validar_admin()) {

            int fila = jtabla_productos.getSelectedRow();
            if (fila == -1) {
                JOptionPane.showMessageDialog(null, "Seleccione un registro");
            } else {
                int dialogButton = JOptionPane.YES_NO_OPTION;
                int dialogResult = JOptionPane.showConfirmDialog(null, "Desea eliminar este recorte?", "Alerta", dialogButton);
                if (dialogResult == JOptionPane.YES_OPTION) {

                    try {
                        DefaultTableModel modelo = (DefaultTableModel) jtabla_productos.getModel();
                        String id = (String) jtabla_productos.getValueAt(fila, 0);//suponiendo que el id lo muestras en la primera columna
                        DB_consultas_R_D.eliminar("recortes_cabecera", id);
                        for (int i = 0; i < modelo.getRowCount(); i++) {
                            if (modelo.getValueAt(i, 0).equals(id)) {
                                modelo.removeRow(i);
                                break;
                            }
                        }
                    } catch (Exception e) {
                        e.printStackTrace();
                    }
                }
            }
        }

    }//GEN-LAST:event_btn_eliminarActionPerformed

