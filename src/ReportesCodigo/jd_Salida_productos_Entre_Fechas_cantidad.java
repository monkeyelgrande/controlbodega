    public Date sumarRestarDiasFecha(Date fecha, int dias) {
        Calendar calendar = Calendar.getInstance();
        calendar.setTime(fecha); // Configuramos la fecha que se recibe
        calendar.add(Calendar.DAY_OF_YEAR, dias); // numero de días a añadir, o restar en caso de días<0
        return calendar.getTime(); // Devuelve el objeto Date con los nuevos días añadidos

    }
    private void btn_consultarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_consultarActionPerformed
        LimpiarModelos();
        String fecha1 = "";
        String fecha2 = "";
        SimpleDateFormat sdf = new SimpleDateFormat("yyyy-MM-dd");
        SimpleDateFormat sdf2 = new SimpleDateFormat("dd-MMM-yyyy");
        fecha1 = sdf.format(jdate_fecha1.getDate());
        fecha2 = sdf.format(jdate_fecha2.getDate());
        modeloBalance.setColumnIdentifiers(new Object[]{"Código", "Descripción", "Cantidad"});

        String consulta = "with consulta as (\n"
                + "SELECT \n"
                + "    p.codigo_barras, \n"
                + "    p.descripcion, \n"
                + "    SUM(fd.cantidad) AS total_cantidad\n"
                + "FROM \n"
                + "    facturas_detalles fd\n"
                + "INNER JOIN \n"
                + "    facturas_cabeceras fc ON fd.id_cabecera = fc.id\n"
                + "INNER JOIN \n"
                + "    productos p ON fd.id_producto = p.id\n"
                + "WHERE \n"
                + "    fc.fecha BETWEEN '" + fecha1 + "' and '" + fecha2 + "'     "
                + "    AND fc.anulado = 1 \n"
                + "    AND fc.tipo_factura IN ('Salida', 'Venta')\n"
                + "GROUP BY \n"
                + "    p.codigo_barras, \n"
                + "    p.descripcion\n"
                + "ORDER BY \n"
                + "    total_cantidad DESC\n"
                + ")\n"
                + "select p.codigo_barras, p.descripcion, coalesce(c.total_cantidad,0) as total_cantidad from productos p left join consulta c on p.codigo_barras=c.codigo_barras order by total_cantidad desc";

        System.out.println(consulta);
        ResultSet rs = DB_consultas_R_D.getTabla(consulta);

        try {
            fecha1 = sdf.format(jdate_fecha1.getDate());
//            fecha2 = sdf.format(jdate_fecha1.getDate());
//            fechaAnterior = sdf.format(sumarRestarDiasFecha(jdate_fecha1.getDate(), -1));
            try {
                while (rs.next()) {
                    modeloBalance.addRow(new Object[]{rs.getString("codigo_barras"), rs.getString("descripcion"),
                        formatea.format(rs.getDouble("total_cantidad"))});
                }
                rs.close();
                // asigna el modelo a la tabla
                jtabla.setModel(modeloBalance);
                TamanosTablaVentas(columnModelBalance);
            } catch (Exception e) {
                System.out.println(e);
            }

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Verifique las fechas", "Alerta", WIDTH);
        }

    }//GEN-LAST:event_btn_consultarActionPerformed

