    public Date sumarRestarDiasFecha(Date fecha, int dias) {
        Calendar calendar = Calendar.getInstance();
        calendar.setTime(fecha); // Configuramos la fecha que se recibe
        calendar.add(Calendar.DAY_OF_YEAR, dias); // numero de días a añadir, o restar en caso de días<0
        return calendar.getTime(); // Devuelve el objeto Date con los nuevos días añadidos

    }
    private void btn_consultarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_consultarActionPerformed
        if (!lbl_id_producto.getText().equals("")) {
            LimpiarModelos();
            String fecha1 = "";
            String fecha2 = "";
            SimpleDateFormat sdf = new SimpleDateFormat("yyyy-MM-dd");
            SimpleDateFormat sdf2 = new SimpleDateFormat("dd-MMM-yyyy");
            fecha1 = sdf.format(jdate_fecha1.getDate());
            fecha2 = sdf.format(jdate_fecha2.getDate());
            modeloBalance.setColumnIdentifiers(new Object[]{"# ingreso", "Descripción", "Proveedor", "Fecha", "Cantidad", "Tipo ingreso"});
            String consulta = "select ic.id as id_ingreso, p.id,p.codigo_barras,p.descripcion, c.nombre as proveedor, ic.fecha, i.cantidad, t.nombre as tipo \n"
                    + "from ingresos_mercancias_detalle i, ingresos_mercancias_cabecera ic, productos p, contactos c, tipo_ingreso t \n"
                    + "where i.id_ingreso_cabecera=ic.id and i.id_producto=p.id and ic.id_proveedor=c.id and ic.id_tipo=t.id and ic.fecha between '" + fecha1 + "' and '" + fecha2 + "' "
                    + "and p.id= '" + lbl_id_producto.getText() + "' order by p.id";

            ResultSet rs = DB_consultas_R_D.getTabla(consulta);

            try {
                fecha1 = sdf.format(jdate_fecha1.getDate());
//            fecha2 = sdf.format(jdate_fecha1.getDate());
//            fechaAnterior = sdf.format(sumarRestarDiasFecha(jdate_fecha1.getDate(), -1));
                try {
                    while (rs.next()) {
                        modeloBalance.addRow(new Object[]{rs.getString("id_ingreso"), rs.getString("descripcion"),
                            rs.getString("proveedor"), rs.getString("fecha"), formatea.format(rs.getDouble("cantidad")),
                            rs.getString("tipo")});
                    }
                    rs.close();
                    // asigna el modelo a la tabla
                    jtable_productos.setModel(modeloBalance);
                    TamanosTablaVentas(columnModelBalance);
                } catch (Exception e) {
                    System.out.println(e);
                }
                calcular_total();

            } catch (Exception e) {
                JOptionPane.showMessageDialog(this, "Verifique las fechas", "Alerta", WIDTH);
            }
        } else {
            JOptionPane.showMessageDialog(this, "Por favor cargue un producto");
        }

    }//GEN-LAST:event_btn_consultarActionPerformed
    public void calcular_total() {
        double total = 0;
        for (int i = 0; i < this.jtable_productos.getRowCount(); i++) {
            total += Double.parseDouble(metodos.EliminaCaracteres(this.jtable_productos.getValueAt(i, 4).toString(), "."));
        }
        lbl_total_salida.setText(formatea.format(total) + "");
    }
