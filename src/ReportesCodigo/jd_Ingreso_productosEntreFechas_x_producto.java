    private void consulta_producto_cod_barras() {
        if (txt_cod_barras.getText().equals("")) {
            JOptionPane.showMessageDialog(this, "Ingrese un codigo de barras");
        } else {
            if (DB_consultas_R_D.consultar_existencia_campo_String("codigo_barras", txt_cod_barras.getText(), "productos") == 1) {
                String codigo = txt_cod_barras.getText();
                ResultSet rs = DB_consultas_R_D.getTabla("select id,codigo_barras,descripcion from productos where codigo_barras ='" + codigo + "'");

                try {
                    while (rs.next()) {
                        lbl_id_producto.setText(rs.getString("id"));
                        lbl_descripcion.setText(rs.getString("descripcion"));

                    }
                    rs.close();
                } catch (SQLException ex) {
                    Logger.getLogger(jd_Salida_productos_entre_fechas_XProducto.class.getName()).log(Level.SEVERE, null, ex);
                }
                btn_consultar.requestFocus();

            }

        }
    }
