    private void btn_guardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_guardarActionPerformed
        if (txt_nombre.getText().equals("")) {
            JOptionPane.showMessageDialog(this, "Por favor ingrese un nombre para la cuenta");
        } else {

            if (DB_consultas_R_D.consultar_existencia_campo_String("nombre", txt_nombre.getText(), "cuentas") > 0) {
                JOptionPane.showMessageDialog(this, "La Cuenta ya se encuentra creada");
                txt_nombre.setText("");
                txt_nombre.requestFocus();
            } else {
                DBcuentas dbcuentas = new DBcuentas();

                Cuentas cuenta = new Cuentas();

                try {
                    cuenta.setId(Integer.parseInt(txt_id.getText()));
                } catch (Exception e) {
                }
                cuenta.setNombre(txt_nombre.getText());

                if (DB_consultas_R_D.consultarId(txt_id.getText(), "cuentas") == 1) {
                    dbcuentas.Actualizar(cuenta);
                } else {
                    dbcuentas.Guardar(cuenta);
                }
                limpiar();
                txt_id.setText(DB_consultas_R_D.cargarId("cuentas"));
                if (chk_cerrar.isSelected()) {
                    this.dispose();
                }
                frm_cuentas.btn_actualizar.doClick();
            }
        }
    }//GEN-LAST:event_btn_guardarActionPerformed

