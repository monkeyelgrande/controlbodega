    private void btn_imprimirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_imprimirActionPerformed
        try {
            SimpleDateFormat sdf2 = new SimpleDateFormat("dd 'de' MMMM 'del' yyyy");
            String fecha1 = sdf2.format(jdate_fecha1.getDate());
            String fecha2 = sdf2.format(jdate_fecha2.getDate());

            DefaultTableModel de = (DefaultTableModel) jtabla_interes.getModel();
            JRTableModelDataSource datasource = new JRTableModelDataSource(de);

            JasperReport report = null;
            Map params = new HashMap();
            params.put("id_factura", "1");
            params.put("fecha_inicio", fecha1);
            params.put("fecha_fin", fecha2);
            params.put("total", lbl_Total_Ingresos.getText());

            params.put("SUBREPORT_DIR", new File("").getAbsolutePath() + "/src/reportes/");

            try {
                try {
                    String cad = new File("").getAbsolutePath() + "/src/reportes/Ingresos_prestamos.jrxml";
                    report = JasperCompileManager.compileReport(cad);
                } catch (Exception e) {
                    JOptionPane.showMessageDialog(this, e);
                }
                JasperPrint jasperPrint = JasperFillManager.fillReport(report, params, datasource);

                JasperViewer view = new JasperViewer(jasperPrint, false);

                JDialog dialog = new JDialog(this);//the owner
                dialog.setContentPane(view.getContentPane());
                dialog.setSize(view.getSize());
                dialog.setModal(true);
                metodos.addEscapeListenerWindowDialog(dialog);
                dialog.setLocationRelativeTo(this);
                dialog.setTitle("Reporte");
                dialog.setVisible(true);
            } catch (Exception e) {
                System.out.println(e);
            }
        } catch (Exception e) {
        }
    }//GEN-LAST:event_btn_imprimirActionPerformed
    public void calcular_total() {
        double total_cantidad = 0;
        for (int i = 0; i < this.jtabla_interes.getRowCount(); i++) {
            total_cantidad += Double.parseDouble(metodos.EliminaCaracteres(this.jtabla_interes.getValueAt(i, 3).toString(), "."));
        }
        lbl_Total_Interes.setText("$ " + metodos.formateador_dinero().format(total_cantidad));

        lbl_Total_Ingresos.setText("$ " + metodos.formateador_dinero().format(total_cantidad));
    }

