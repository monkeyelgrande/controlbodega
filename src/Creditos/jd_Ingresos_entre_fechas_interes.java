    public void LimpiarModelos() {
        try {
            for (int i = 0; i < jtabla_interes.getRowCount(); i++) {
                modelo1.removeRow(i);
                i -= 1;
            }
        } catch (Exception e) {
        }

    }
    private void btn_consultarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_consultarActionPerformed
        LimpiarModelos();
        String fecha1 = "";
        String fecha2 = "";
        SimpleDateFormat sdf = new SimpleDateFormat("yyyy-MM-dd");
        SimpleDateFormat sdf2 = new SimpleDateFormat("dd-MMM-yyyy");
        fecha1 = sdf.format(jdate_fecha1.getDate());
        fecha2 = sdf.format(jdate_fecha2.getDate());

        String consulta = "SELECT \n"
                + "    pa.id AS id_pago,\n"
                + "    c.nombre AS cliente_nombre,\n"
                + "    (pa.interes+pa.capital) AS monto_pago,\n"
                + "    pa.fecha AS fecha_pago,\n"
                + "CASE \n"
                + "        WHEN pa.capital > 0 THEN 'Capital'\n"
                + "        WHEN pa.interes > 0 THEN 'Interés'\n"
                + "        ELSE 'Sin Pago'\n"
                + "    END AS tipo_pago "
                + "FROM \n"
                + "    pagos_prestamos pa\n"
                + "JOIN \n"
                + "    prestamos a ON pa.id_prestamo = a.id\n"
                + "JOIN \n"
                + "    contactos c ON a.id_cliente = c.id\n"
                + "WHERE \n"
                + "    pa.fecha BETWEEN '" + fecha1 + "' and '" + fecha2 + "'\n"
                + "ORDER BY \n"
                + "    pa.fecha, c.nombre;";

        ResultSet rs = DB_consultas_R_D.getTabla(consulta);

        modelo1.setColumnIdentifiers(new Object[]{"Id prestamo", "Cliente", "Tipo", "Pago", "Fecha"});
        try {
            while (rs.next()) {
                // añade los resultado a al modelo de tabla
                modelo1.addRow(new Object[]{rs.getString("id_pago"), rs.getString("cliente_nombre"), rs.getString("tipo_pago"), metodos.formateador_dinero().format(rs.getDouble("monto_pago")),
                    sdf2.format(rs.getDate("fecha_pago"))});
            }
            rs.close();
            // asigna el modelo a la tabla
            jtabla_interes.setModel(modelo1);
            TamanosTablaVentas(columnModelVentas);
            calcular_total();
            btn_imprimir.setEnabled(true);

        } catch (Exception e) {
            System.out.println(e);
        }


    }//GEN-LAST:event_btn_consultarActionPerformed

