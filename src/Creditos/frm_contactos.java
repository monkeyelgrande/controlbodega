    private void btn_eliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_eliminarActionPerformed

        int fila = jtabla_contactos.getSelectedRow();
        if (fila == -1) {
            JOptionPane.showMessageDialog(null, "Seleccione un registro");
        } else {
            String id = (String) jtabla_contactos.getValueAt(fila, 0);//suponiendo que el id lo muestras en la primera columna
            if (DB_consultas_R_D.validar_admin("Contactos", "Eliminar", "Se edito el registro con el id: " + id)) {
                int dialogButton = JOptionPane.YES_NO_OPTION;
                int dialogResult = JOptionPane.showConfirmDialog(null, "Desea eliminar este contactos?", "Alerta", dialogButton);
                if (dialogResult == JOptionPane.YES_OPTION) {
                    try {
                        DefaultTableModel modelo = (DefaultTableModel) jtabla_contactos.getModel();
                        DB_consultas_R_D.eliminar("contactos", id);
                        for (int i = 0; i < modelo.getRowCount(); i++) {
                            if (modelo.getValueAt(i, 0).equals(id)) {
                                modelo.removeRow(i);
                                break;
                            }
                        }
                    } catch (Exception e) {
                        e.printStackTrace();
                    }
                }
            }
        }
    }//GEN-LAST:event_btn_eliminarActionPerformed

    private void btn_editarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_editarActionPerformed

        jif_crear_contacto = new jif_crear_contactos();
        int fila = jtabla_contactos.getSelectedRow();
        if (fila < 0) {
            JOptionPane.showMessageDialog(this, "Seleccione un registro");
        } else {
            String id = "" + jtabla_contactos.getValueAt(fila, 0);

            ResultSet rs = DB_consultas_R_D.getTabla("select * from contactos where id =" + id);
            try {
                while (rs.next()) {
                    jif_crear_contactos.txt_id_contacto.setText(rs.getString("id"));
                    jif_crear_contactos.txt_nombre.setText(rs.getString("nombre"));
                    jif_crear_contactos.txt_cedula.setText(rs.getString("cedula"));
                    jif_crear_contactos.txt_celular.setText(rs.getString("celular"));
                    jif_crear_contactos.txt_telefono.setText(rs.getString("telefono"));
                    jif_crear_contactos.txt_direccion.setText(rs.getString("direccion"));
                    jif_crear_contactos.txt_email.setText(rs.getString("email"));
                    jif_crear_contactos.txt_cupo.setText(metodos.formateador_dinero().format(rs.getDouble("cupo")));
                    jif_crear_contactos.txt_interes.setText(metodos.formateador_un_decimal().format(rs.getDouble("interes")));
                    jif_crear_contactos.txt_ciudad.setText(rs.getString("ciudad"));
                    jif_crear_contactos.jtxa_observaciones.setText(rs.getString("observaciones"));
                    if (rs.getInt("empleado") == 1) {
                        jif_crear_contactos.chk_empleado.setSelected(true);
                    } else {
                        jif_crear_contactos.chk_empleado.setSelected(false);
                    }
      
                    if (rs.getInt("antiguo") == 1) {
                        jif_crear_contactos.chk_antiguo.setSelected(true);
                    } else {
                        jif_crear_contactos.chk_antiguo.setSelected(false);
                    }

                }
                rs.close();

            } catch (SQLException ex) {
                Logger.getLogger(frm_contactos.class.getName()).log(Level.SEVERE, null, ex);
            }
            if (ver) {
                jif_crear_contacto.txt_nombre.setEditable(false);
                jif_crear_contacto.txt_cedula.setEditable(false);
                jif_crear_contacto.txt_celular.setEditable(false);
                jif_crear_contacto.txt_telefono.setEditable(false);
                jif_crear_contacto.txt_direccion.setEditable(false);
                jif_crear_contacto.txt_ciudad.setEditable(false);
                jif_crear_contacto.txt_email.setEditable(false);
                jif_crear_contacto.txt_cupo.setEditable(false);
                jif_crear_contacto.jtxa_observaciones.setEditable(false);
                jif_crear_contacto.btn_guardar.setEnabled(false);
                jif_crear_contacto.btn_limpiar.setEnabled(false);
                jif_crear_contacto.chk_cerrar.setEnabled(false);
                jif_crear_contacto.btn_editar.setVisible(true);
                jif_crear_contacto.chk_empleado.setEnabled(false);
                jif_crear_contacto.chk_antiguo.setEnabled(false);
                jif_crear_contacto.txt_interes.setEnabled(false);
                ver = false;
                jif_crear_contacto.show();
            } else {

                if (DB_consultas_R_D.validar_admin("Contactos", "Editar", "Se edito el registro con el id: " + id)) {

                    ver = false;
                    jif_crear_contacto.show();
                    jif_crear_contactos.txt_nombre.requestFocus();
                }
            }

        }

    }//GEN-LAST:event_btn_editarActionPerformed

