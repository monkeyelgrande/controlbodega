    public void actualizar() {
        try {
            for (int i = 0; i < modelo.getRowCount(); i++) {
                modelo.removeRow(i);
                i -= 1;
            }
        } catch (Exception e) {
        }

        ResultSet rs = DB_consultas_R_D.getTabla("select id,nombre,cedula,contacto as celular,direccion, cupo from contactos order by id");

        modelo.setColumnIdentifiers(new Object[]{"id", "Nombre", "Cédula", "Celular", "Cupo"});
        try {
            while (rs.next()) {
                // añade los resultado a al modelo de tabla
                modelo.addRow(new Object[]{rs.getString("id"), rs.getString("nombre"), rs.getString("cedula"),
                    rs.getString("celular"), metodos.formateador_dinero().format(rs.getDouble("cupo"))});
            }
            rs.close();
            // asigna el modelo a la tabla
            jtabla_contactos.setModel(modelo);
        } catch (Exception e) {
            System.out.println(e);
        }
    }
