    private void btn_guardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_guardarActionPerformed

        if (txt_cedula.getText().equals("") || txt_nombre.getText().equals("")) {
            JOptionPane.showMessageDialog(this, "Por favor ingrese un nombre para el modelo");
        } else {

            DBcontactos dbclientes = new DBcontactos();
            Contactos contacto = new Contactos();

            contacto.setId(Integer.parseInt(DB_consultas_R_D.cargarId("contactos")));

            contacto.setNombre(txt_nombre.getText());
            contacto.setCedula(txt_cedula.getText());
            contacto.setDireccion(txt_direccion.getText());
            contacto.setCelular(txt_celular.getText());
            contacto.setTelefono("");
            contacto.setEmail("");
            contacto.setCiudad("");
            contacto.setObservaciones("");
            contacto.setCupo(Double.parseDouble(metodos.EliminaCaracteres(txt_cupo.getText(), ".")));
            contacto.setEmpleado(0);
            if (chk_antiguo.isSelected()) {
                contacto.setAntiguo(1);
            } else {
                contacto.setAntiguo(0);
            }
            if (dbclientes.Guardar(contacto) == 1) {
                if (formulario.equals("credito")) {
                    DefaultComboBoxModel modeloCombo = (DefaultComboBoxModel) jif_crear_credito.cbx_contacto.getModel();
                    modeloCombo.addElement(new Contactos(contacto.getId(), contacto.getNombre()));
                    jif_crear_credito.cbx_contacto.setModel(modeloCombo);
                    jif_crear_credito.cbx_contacto.setSelectedItem(txt_nombre.getText());
                    jif_crear_credito.traer_cupo();
                    this.dispose();

                }
            }

        }
    }//GEN-LAST:event_btn_guardarActionPerformed
