            PreparedStatement psql = con.prepareStatement(SQL);
            psql.setString(1, contacto.getNombre());
            psql.setString(2, contacto.getCedula());
            psql.setString(3, contacto.getDireccion());
            psql.setString(4, contacto.getCiudad());
            psql.setString(5, contacto.getContacto());
            psql.setString(6, contacto.getContacto2());
            psql.setInt(7, contacto.getDescuento());
            psql.setString(8, contacto.getEmail());
            psql.setString(9, contacto.getFormapago());
            psql.setString(10, contacto.getCuenta());
            psql.setString(11, contacto.getTipo_cuenta());
            psql.setString(12, contacto.getNumero_cuenta());
            psql.setString(13, contacto.getObservaciones());
            psql.setInt(14, contacto.getProveedor());
            psql.setInt(15, predeterminado);
            psql.setInt(16, contacto.getId());

            psql.executeUpdate();
