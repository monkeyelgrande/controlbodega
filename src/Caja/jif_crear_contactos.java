    private void txt_cedulaFocusLost(java.awt.event.FocusEvent evt) {//GEN-FIRST:event_txt_cedulaFocusLost
        if (DB_consultas_R_D.consultar_existencia_campo_String("cedula", txt_cedula.getText(), "contactos") == 1) {
            int dialogButton = JOptionPane.YES_NO_OPTION;
            int dialogResult = JOptionPane.showConfirmDialog(null, "El numero de cédula ingresado ya esta registrado.\n ¿Desea cargar los datos?", "Alerta", dialogButton);
            if (dialogResult == JOptionPane.YES_OPTION) {
                ResultSet rs = DB_consultas_R_D.getTabla("select * from contactos where cedula ='" + txt_cedula.getText() + "'");
                try {
                    while (rs.next()) {
                        txt_id_cliente.setText(rs.getString("id"));
                        txt_nombre.setText(rs.getString("nombre"));
                        txt_cedula.setText(rs.getString("cedula"));
                        txt_contacto.setText(rs.getString("contacto"));
                        txt_contacto2.setText(rs.getString("contacto2"));
                        txt_direccion.setText(rs.getString("direccion"));
                        txt_descuento.setText(rs.getString("descuento"));
                        txt_email.setText(rs.getString("email"));
                        txt_ciudad.setText(rs.getString("ciudad"));
                        txt_forma_pago.setText(rs.getString("forma_pago"));
                        txt_banco_cuenta.setText(rs.getString("cuenta"));
                        txt_tipo_cuenta.setText(rs.getString("tipo_cuenta"));
                        txt_Numero_cuenta.setText(rs.getString("numero_cuenta"));
                        jtxa_observaciones.setText(rs.getString("observaciones"));

                    }
                    rs.close();

                } catch (SQLException ex) {
                    Logger.getLogger(jif_crear_contactos.class.getName()).log(Level.SEVERE, null, ex);
                }
            } else {
                txt_cedula.setText("");
                txt_cedula.requestFocus();
            }
        }
    }//GEN-LAST:event_txt_cedulaFocusLost


