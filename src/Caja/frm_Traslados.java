    private void btn_eliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_eliminarActionPerformed
        int fila = jtabla_gastos.getSelectedRow();
        if (fila == -1) {
            JOptionPane.showMessageDialog(null, "Seleccione un registro");
        } else {
            int dialogButton = JOptionPane.YES_NO_OPTION;
            int dialogResult = JOptionPane.showConfirmDialog(null, "Desea eliminar este ingreso?", "Alerta", dialogButton);
            if (dialogResult == JOptionPane.YES_OPTION) {

                try {
                    DefaultTableModel modelo = (DefaultTableModel) jtabla_gastos.getModel();
                    String id = jtabla_gastos.getValueAt(fila, 0).toString();
                    String id_ingreso = jtabla_gastos.getValueAt(fila, 6).toString();
                    String id_egreso = jtabla_gastos.getValueAt(fila, 7).toString();
                    // primero la transferencia (tiene FK hacia el par)
                    DB_consultas_R_D.eliminar("transferencias", id);
                    DB_consultas_R_D.eliminar("ingresos", id_ingreso);
                    DB_consultas_R_D.eliminar("egresos", id_egreso);
                    for (int i = 0; i < modelo.getRowCount(); i++) {
                        if (modelo.getValueAt(i, 0).equals(id)) {
                            modelo.removeRow(i);
                            limpiar();
                            break;
                        }
                    }
                } catch (Exception e) {
                    e.printStackTrace();
                }
            }
        }
    }//GEN-LAST:event_btn_eliminarActionPerformed


