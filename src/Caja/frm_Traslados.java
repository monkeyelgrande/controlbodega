    private void btn_imprimir1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_imprimir1ActionPerformed
        int fila = jtabla_gastos.getSelectedRow();
        if (fila == -1) {
            JOptionPane.showMessageDialog(null, "Seleccione un registro");
        } else {
            int dialogButton = JOptionPane.YES_NO_OPTION;
            int dialogResult = JOptionPane.showConfirmDialog(null, "¿Desea imrpimir este ingreso?", "Alerta", dialogButton);
            if (dialogResult == JOptionPane.YES_OPTION) {
                String id = jtabla_gastos.getValueAt(fila, 0).toString();//suponiendo que el id lo muestras en la primera columna

                String consulta = "select t.id, t.fecha, t.hora, t.descripcion, t.total \n"
                + "from transferencias t \n"
                + "where t.id = " + id;
                ResultSet rs = DB_consultas_R_D.getTabla(consulta);

                ImprimirPNG_traslado imprimir = null;
                try {
                    while (rs.next()) {
                        imprimir = new ImprimirPNG_traslado(rs.getString("fecha") + " / " + rs.getString("hora"), rs.getString("id"),
                            jtabla_gastos.getValueAt(fila, 1).toString(), jtabla_gastos.getValueAt(fila, 2).toString(),
                            metodos.formateador_dinero().format(rs.getDouble("total")), rs.getString("descripcion"), "TRASLADO");
                    }
                    rs.close();

                } catch (SQLException ex) {
                    System.out.println("");
                }
                imprimir.generarYGuardarImagen();
            }
        }
    }//GEN-LAST:event_btn_imprimir1ActionPerformed

    public void actualizar(String fecha) {
        try {
            for (int i = 0; i < jtabla_gastos.getRowCount(); i++) {
                modelo.removeRow(i);
                i -= 1;
            }
        } catch (Exception e) {
        }
        ResultSet rs;
        if (fecha.equals("hoy")) {
            rs = DB_consultas_R_D.getTabla("select i.id,fo.nombre as nombre_origen, fd.nombre as nombre_destino,i.total,i.descripcion,i.fecha, i.id_ingreso, i.id_egreso "
                    + "from transferencias i, fondos fo, fondos fd "
                    + "where i.id_fondo_origen=fo.id and i.id_fondo_destino=fd.id and i.fecha=CURRENT_DATE order by i.fecha desc, i.id desc");
        } else {
            rs = DB_consultas_R_D.getTabla("select i.id,fo.nombre as nombre_origen, fd.nombre as nombre_destino,i.total,i.descripcion,i.fecha, i.id_ingreso, i.id_egreso  "
                    + "from transferencias i,fondos fo, fondos fd "
                    + "where i.id_fondo_origen=fo.id and i.id_fondo_destino=fd.id order by i.fecha desc, i.id desc");
        }

        modelo.setColumnIdentifiers(new Object[]{"id", "Fondo origen", "Fondo destino", "Total", "Descripcion", "Fecha", "Id ingreso", "Id Egreso"});
        try {
            while (rs.next()) {

                modelo.addRow(new Object[]{rs.getString("id"), rs.getString("nombre_origen"), rs.getString("nombre_destino"), formatea.format(rs.getDouble("total")),
                    rs.getString("descripcion"), rs.getDate("fecha"), rs.getInt("id_ingreso"), rs.getInt("id_egreso")});
            }
            rs.close();
            // asigna el modelo a la tabla
            jtabla_gastos.setModel(modelo);
            TamanosTablaAbonos();
        } catch (Exception e) {
            System.out.println(e);
        }
    }

